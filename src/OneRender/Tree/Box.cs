using OneRender.Style;

namespace OneRender.Tree;

/// <summary>What a <see cref="Box"/> is.</summary>
public enum BoxKind : byte
{
    /// <summary>A box with a formatting context of its own that lays out its children: a block container, flex, grid or table box, an inline-block, or an anonymous block. See <see cref="Box.Context"/>.</summary>
    Container,

    /// <summary>A non-atomic inline box (<c>display: inline</c>): its children flow in the line boxes of an ancestor's inline formatting context.</summary>
    Inline,

    /// <summary>A run of text; the text is that of <see cref="Box.Node"/>. Text boxes are the anonymous inline boxes of CSS2 §9.2.2.1.</summary>
    Text,

    /// <summary>Replaced content (<c>img</c>, <c>video</c>, <c>canvas</c>, <c>iframe</c>, <c>embed</c>, <c>object</c>, inline <c>svg</c>); its natural size is on <see cref="Box.Node"/>.</summary>
    Replaced,

    /// <summary>A forced line break (<c>br</c>).</summary>
    LineBreak,

    /// <summary>A list item's marker placeholder (<c>::marker</c>). It has no children and no text yet; the generated-content support fills it in.</summary>
    Marker,
}

/// <summary>Whether a box takes part in a block or an inline formatting context in its parent (CSS Display 3 §2.1).</summary>
public enum BoxLevel : byte
{
    /// <summary>Block-level.</summary>
    Block,

    /// <summary>Inline-level.</summary>
    Inline,
}

/// <summary>The formatting context a container box establishes or participates in for its children.</summary>
public enum FormattingContext : byte
{
    /// <summary>Not a container (inline, text, replaced, line break, marker).</summary>
    None,

    /// <summary>A block container in normal flow (<c>display: block</c>, <c>list-item</c>, anonymous blocks). It may or may not start a new block formatting context; layout decides from the style.</summary>
    Block,

    /// <summary>A block container that always starts a new block formatting context (<c>flow-root</c>, <c>inline-block</c>).</summary>
    FlowRoot,

    /// <summary>A flex container.</summary>
    Flex,

    /// <summary>A grid container.</summary>
    Grid,

    /// <summary>A table box. Wrapper and anonymous table boxes are added by the table support, not here.</summary>
    Table,

    /// <summary><c>table-row-group</c>.</summary>
    TableRowGroup,

    /// <summary><c>table-header-group</c>.</summary>
    TableHeaderGroup,

    /// <summary><c>table-footer-group</c>.</summary>
    TableFooterGroup,

    /// <summary><c>table-row</c>.</summary>
    TableRow,

    /// <summary><c>table-cell</c>; its content is a block container.</summary>
    TableCell,

    /// <summary><c>table-column-group</c>.</summary>
    TableColumnGroup,

    /// <summary><c>table-column</c>.</summary>
    TableColumn,

    /// <summary><c>table-caption</c>; its content is a block container.</summary>
    TableCaption,

    /// <summary><c>ruby</c>; boxes only.</summary>
    Ruby,
}

/// <summary>How a container's children are laid out, settled when the container is complete.</summary>
public enum ChildLayout : byte
{
    /// <summary>No children, or none that take part in layout.</summary>
    Empty,

    /// <summary>Every in-flow child is inline-level: the container establishes an inline formatting context (CSS2 §9.4.2).</summary>
    Inline,

    /// <summary>Every in-flow child is block-level, or the container is a flex, grid or table container: its children are laid out by the context's own algorithm.</summary>
    Block,
}

/// <summary>Extra facts about a box.</summary>
[Flags]
public enum BoxTraits : ushort
{
    /// <summary>No flags.</summary>
    None = 0,

    /// <summary>Generated by the engine with no element behind it: the anonymous block boxes of CSS2 §9.2.1.1. Its style inherits from its parent's.</summary>
    Anonymous = 1,

    /// <summary>A later piece of an inline box that a block-level descendant split in two (CSS2 §9.2.1.1). It shares its element with the first piece, found through <see cref="Box.NextPiece"/>.</summary>
    Continuation = 2,

    /// <summary>The box's element has <c>display: list-item</c>.</summary>
    ListItem = 4,

    /// <summary>A marker positioned outside the list item's content (<c>list-style-position: outside</c>). It is a direct child that never takes part in line boxes.</summary>
    OutsideMarker = 8,

    /// <summary>Floated, or absolutely or fixed positioned: out of flow.</summary>
    OutOfFlow = 16,

    /// <summary>Its <c>display</c> was blockified because its parent is a flex or grid container (CSS Display 3 §2.7).</summary>
    Blockified = 32,

    /// <summary>A block container that has at least one in-flow block-level child before wrapping; internal bookkeeping that stays set.</summary>
    HasBlockChild = 64,

    /// <summary>A block-level box inside an inline box that the engine could not split because the inline nesting passed the limit; it is laid out as an inline-block.</summary>
    UnsplitBlockInInline = 128,
}

/// <summary>A handle to a box of a <see cref="BoxTree"/>. Cheap to copy; valid until the tree is rebuilt.</summary>
public readonly struct Box : IEquatable<Box>
{
    internal Box(BoxTree tree, int index)
    {
        Tree = tree;
        Index = index;
    }

    /// <summary>The tree the box belongs to; null for the default value.</summary>
    public BoxTree? Tree { get; }

    /// <summary>The box's position in the tree's columns.</summary>
    public int Index { get; }

    /// <summary>True for the default value, which refers to no box.</summary>
    public bool IsNull => Tree is null;

    /// <summary>What the box is.</summary>
    public BoxKind Kind => (BoxKind)Tree!.KindOf(Index);

    /// <summary>Block-level or inline-level in its parent.</summary>
    public BoxLevel Level => (BoxLevel)Tree!.LevelOf(Index);

    /// <summary>The formatting context of a container; <see cref="FormattingContext.None"/> for other kinds.</summary>
    public FormattingContext Context => (FormattingContext)Tree!.ContextOf(Index);

    /// <summary>How the children are laid out; settled once the tree is built.</summary>
    public ChildLayout ChildLayout => (ChildLayout)Tree!.ChildLayoutOf(Index);

    /// <summary>Extra facts.</summary>
    public BoxTraits Flags => (BoxTraits)Tree!.FlagsOf(Index);

    /// <summary>True for boxes with no element behind them.</summary>
    public bool IsAnonymous => (Flags & BoxTraits.Anonymous) != 0;

    /// <summary>True for an inline-level container, replaced box or marker that lays out as one unit in a line (an atomic inline).</summary>
    public bool IsAtomicInline => Level == BoxLevel.Inline && Kind is BoxKind.Container or BoxKind.Replaced;

    /// <summary>The style row.</summary>
    public StyleId Style => Tree!.StyleOf(Index);

    /// <summary>The computed values of the box. For anonymous boxes the inherited values of the parent and initial values elsewhere.</summary>
    public ref readonly ComputedValues Values => ref Tree!.Styled.Styles[Tree.StyleOf(Index)];

    /// <summary>The styled node the box was made from; the null handle for anonymous boxes.</summary>
    public StyledNode Node => Tree!.NodeOf(Index);

    /// <summary>The text of a <see cref="BoxKind.Text"/> box, unprocessed (white space is collapsed by inline layout). Empty for other kinds.</summary>
    public ReadOnlySpan<char> Text => Kind == BoxKind.Text ? Node.Text : default;

    /// <summary>The parent, or the null handle for the root.</summary>
    public Box Parent => Tree!.Make(Tree.ParentOf(Index));

    /// <summary>The first child, or the null handle.</summary>
    public Box FirstChild => Tree!.Make(Tree.FirstChildOf(Index));

    /// <summary>The last child, or the null handle.</summary>
    public Box LastChild => Tree!.Make(Tree.LastChildOf(Index));

    /// <summary>The next sibling, or the null handle.</summary>
    public Box NextSibling => Tree!.Make(Tree.NextSiblingOf(Index));

    /// <summary>The previous sibling, or the null handle.</summary>
    public Box PreviousSibling => Tree!.Make(Tree.PreviousSiblingOf(Index));

    /// <summary>For an inline box split around a block-level child, the next piece of the same element; the null handle for the last piece and for other boxes.</summary>
    public Box NextPiece => Tree!.Make(Tree.NextPieceOf(Index));

    /// <inheritdoc />
    public bool Equals(Box other) => ReferenceEquals(Tree, other.Tree) && Index == other.Index;

    /// <inheritdoc />
    public override bool Equals(object? obj) => obj is Box b && Equals(b);

    /// <inheritdoc />
    public override int GetHashCode() => Index;

    /// <summary>Equality.</summary>
    public static bool operator ==(Box left, Box right) => left.Equals(right);

    /// <summary>Inequality.</summary>
    public static bool operator !=(Box left, Box right) => !left.Equals(right);

    /// <inheritdoc />
    public override string ToString() => Tree is null ? "(null)" : Kind + "#" + Index.ToString(System.Globalization.CultureInfo.InvariantCulture);
}
