#!/usr/bin/env bash
# Checks that every piece of third-party material committed to the repository has a notice in THIRD-PARTY-NOTICES.md.
#
#   tools/ci/check-notices.sh
#
# Run from anywhere inside the checkout. Exit status 1 and a list of problems when something is missing; 0 when clean.
# What it looks at:
#   - every font file: a fonts package folder must hold OFL.txt and a MANIFEST.tsv that lists each font with a SHA-256 that
#     matches the file; any other font must sit in a folder the notices name (and that has its OFL.txt);
#   - every folder that holds copies of web-platform-tests files (a path component starting with "wpt-") is named in the notices;
#   - every file carrying a Tailwind CSS banner, and every page or style sheet mentioning daisyUI or Flowbite markup compiled in,
#     is named in the notices;
#   - every other image, font or PDF outside results/ is in a folder the notices name, or in the list of files we wrote below.
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
notices=THIRD-PARTY-NOTICES.md
problems=0
fail() { echo "MISSING: $*"; problems=$((problems + 1)); }
named() { grep -qF -- "$1" "$notices"; }

# Binary or generated files that are our own work, by folder (generated by this repository's tests and samples).
own_dirs=(
  "tests/OneRender.Tests/Golden"      # pictures our rasterizer wrote; the tests compare against them
  "samples/InvoiceApp/wwwroot/img"    # the sample's fictional logo
)
is_own() { local f=$1 d; for d in "${own_dirs[@]}"; do [[ $f == "$d"/* ]] && return 0; done; return 1; }

# 1. Fonts packages.
for dir in src/OneRender.Fonts*/fonts; do
  [[ -d $dir ]] || continue
  manifest=$dir/MANIFEST.tsv
  [[ -f $manifest ]] || { fail "$dir has no MANIFEST.tsv"; continue; }
  if ! find "$dir" -name OFL.txt | grep -q .; then fail "$dir has no OFL.txt"; fi
  while IFS= read -r font; do
    rel=${font#"$dir"/}
    line=$(awk -F'\t' -v p="$rel" '$1=="file" && $2==p {print $NF}' "$manifest" | head -1)
    if [[ -z $line ]]; then fail "$font is not listed in $manifest"; continue; fi
    actual=$(sha256sum "$font" | cut -d' ' -f1)
    # The last column is the file's hash for a direct download; for archive members the per-file hash is the fifth column.
    want=$(awk -F'\t' -v p="$rel" '$1=="file" && $2==p {print $5}' "$manifest" | head -1)
    if [[ $want != "$actual" ]]; then fail "$font: SHA-256 $actual differs from the manifest ($want)"; fi
  done < <(find "$dir" -type f \( -name '*.ttf' -o -name '*.otf' -o -name '*.ttc' -o -name '*.woff' -o -name '*.woff2' \) | sort)
done

# 2. Fonts elsewhere.
while IFS= read -r font; do
  case $font in src/OneRender.Fonts*/fonts/*) continue ;; esac
  dir=$(dirname "$font")
  named "$dir" || fail "$font: folder $dir is not named in $notices"
  [[ -f $dir/OFL.txt ]] || fail "$font: $dir has no OFL.txt"
done < <(git ls-files | grep -iE '\.(ttf|otf|ttc|woff2?)$' || true)

# 3. web-platform-tests copies (results/ holds our own result files, which name tests but contain none).
while IFS= read -r d; do
  named "$d" || fail "$d holds web-platform-tests files and is not named in $notices"
done < <(git ls-files | grep -vE '^results/' | grep -E '(^|/)wpt-[^/]+/' | sed -E 's|(.*/wpt-[^/]+)/.*|\1|' | sort -u)
named "web-platform-tests" || fail "no web-platform-tests section"
grep -qF "Redistributions of source code must retain the above copyright notice" "$notices" || fail "the BSD-3-Clause text for web-platform-tests is missing"

# 4. Tailwind, daisyUI, Flowbite.
while IFS= read -r f; do
  named "$f" || fail "$f carries a Tailwind CSS banner and is not named in $notices"
done < <(git grep -lF 'tailwindcss v' -- '*.css' || true)
while IFS= read -r f; do
  named "$f" || named "$(dirname "$f")" || fail "$f uses daisyUI or Flowbite output and is not named in $notices"
done < <(git grep -lEi '(\.daisy|--color-base-100|flowbite-)' -- '*.css' || true)
for lic in 'Tailwind CSS' 'daisyUI' 'Flowbite'; do named "$lic" || fail "no notice for $lic"; done
grep -qF "The above copyright notice and this permission notice shall be included" "$notices" || fail "the MIT permission sentence is missing"

# 5. Other binary material outside results/.
while IFS= read -r f; do
  is_own "$f" && continue
  case $f in results/*|src/OneRender.Fonts*/fonts/*|testdata/fonts/*) continue ;; esac
  named "$f" || named "$(dirname "$f")" || fail "$f: an image, font or PDF whose folder is not named in $notices and is not listed as our own work"
done < <(git ls-files | grep -iE '\.(png|jpe?g|gif|webp|svg|pdf|ico|bmp)$' || true)

if [[ $problems -gt 0 ]]; then
  echo "$problems problem(s)."
  exit 1
fi
echo "notices: every committed third-party item has a notice."
